"""Load the generated sales tables into BigQuery.

Usage:
    python3 -m sales.load --project YOUR_PROJECT_ID --dry-run
    python3 -m sales.load --project YOUR_PROJECT_ID
"""

import argparse
import json
import sys
from pathlib import Path

from catalog.schema import row_errors
from sales.schema import TABLES

DESCRIPTION = "Synthetic sales for the home decor catalog, generated by sales/generate.py."


def check(path, fields):
    count, problems = 0, []
    with Path(path).open(encoding="utf-8") as f:
        for number, line in enumerate(f, start=1):
            if line.strip():
                count += 1
                errors = row_errors(json.loads(line), fields)
                if errors:
                    problems.append((number, errors))
    return count, problems


def load_table(client, path, table_id, fields, location):
    from google.cloud import bigquery

    job_config = bigquery.LoadJobConfig(
        schema=[bigquery.SchemaField(n, t, mode=m, description=d) for n, t, m, d in fields],
        source_format=bigquery.SourceFormat.NEWLINE_DELIMITED_JSON,
        write_disposition=bigquery.WriteDisposition.WRITE_TRUNCATE,
    )
    with Path(path).open("rb") as f:
        client.load_table_from_file(f, table_id, job_config=job_config, location=location).result()
    table = client.get_table(table_id)
    table.description = DESCRIPTION
    client.update_table(table, ["description"])
    return table.num_rows


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--project", required=True)
    parser.add_argument("--dataset", default="home_decor")
    parser.add_argument("--location", default="asia-south1")
    parser.add_argument("--dir", default="data/sales")
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args(argv)

    failed = False
    for name, fields in TABLES.items():
        count, problems = check(Path(args.dir) / f"{name}.jsonl", fields)
        print(f"{name}: {count} rows, {len(problems)} invalid")
        for number, errors in problems[:5]:
            print(f"  line {number}: {'; '.join(errors)}")
        failed = failed or bool(problems)
    if failed:
        sys.exit("Invalid rows found. Nothing loaded.")
    if args.dry_run:
        return

    from google.cloud import bigquery

    client = bigquery.Client(project=args.project)
    for name, fields in TABLES.items():
        rows = load_table(client, Path(args.dir) / f"{name}.jsonl",
                          f"{args.project}.{args.dataset}.{name}", fields, args.location)
        print(f"Loaded {rows} rows into {args.dataset}.{name}")


if __name__ == "__main__":
    main()
